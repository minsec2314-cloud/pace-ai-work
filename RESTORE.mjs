// Main-owned recovery helper. No deployment, authentication or model request.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {execFileSync,spawnSync} from 'node:child_process';
const kit=path.dirname(fileURLToPath(import.meta.url));
const descriptor=JSON.parse(fs.readFileSync(path.join(kit,'RECOVERY.json'),'utf8'));
const hash=b=>createHash('sha256').update(b).digest('hex');
for(const [file,expected]of [['repo.git.bundle',descriptor.bundleSha256],['working-tree.patch',descriptor.patchSha256],['CHECKPOINT_AS_RECEIVED.json',descriptor.checkpointSha256]])if(hash(fs.readFileSync(path.join(kit,file)))!==expected)throw Error('Recovery input hash mismatch: '+file);
const patch=fs.readFileSync(path.join(kit,'working-tree.patch'),'utf8');
const allowed=['PACE_AI_WORKSPACE/source/tests/ai.test.mjs','PACE_AI_WORKSPACE/source/tests/quiz-review.test.mjs'];
const changed=[...patch.matchAll(/^diff --git a\/(.+) b\/(.+)$/gm)].map(m=>{if(m[1]!==m[2])throw Error('Unexpected rename');return m[1];}).sort();
if(JSON.stringify(changed)!==JSON.stringify(allowed))throw Error('Unexpected draft paths');
if(!process.argv[2])throw Error('Supply a new empty target directory');
const target=path.resolve(process.argv[2]);
if(target===kit||target.startsWith(kit+path.sep))throw Error('Use a separate recovery target');
if(fs.existsSync(target)&&fs.readdirSync(target).length)throw Error('Target contains files; preserved without overwrite');
fs.mkdirSync(target,{recursive:true});
const hooks=path.join(target,'empty-hooks');fs.mkdirSync(hooks);
const repo=path.join(target,'checkout');
const git=(args,cwd=target)=>execFileSync('git',['-c','core.autocrlf=false','-c','core.fsmonitor=false','-c','core.hooksPath='+hooks,...args],{cwd,maxBuffer:32*1024*1024,env:{...process.env,GIT_TERMINAL_PROMPT:'0'}});
git(['clone','--branch',descriptor.branch,'--',path.join(kit,'repo.git.bundle'),repo]);
if(git(['rev-parse','HEAD'],repo).toString().trim()!==descriptor.headCommit)throw Error('Restored HEAD mismatch');
git(['apply','--check',path.join(kit,'working-tree.patch')],repo);
git(['apply',path.join(kit,'working-tree.patch')],repo);
const tracked=git(['ls-files','-z'],repo).toString().split('\0').filter(Boolean);
if(tracked.length!==descriptor.expectedCheckout.length)throw Error('Tracked count');
for(const f of descriptor.expectedCheckout){if(!tracked.includes(f.path)||hash(fs.readFileSync(path.join(repo,f.path)))!==f.sha256)throw Error('Restored file hash: '+f.path);}
const state=path.join(target,'recovery-state');fs.mkdirSync(state);
fs.copyFileSync(path.join(kit,'CHECKPOINT_AS_RECEIVED.json'),path.join(state,'CHECKPOINT_AS_RECEIVED.json'));
fs.copyFileSync(path.join(kit,'DRAFT_CHECKPOINT_AS_RECEIVED.json'),path.join(state,'DRAFT_CHECKPOINT_AS_RECEIVED.json'));
const source=path.join(repo,'PACE_AI_WORKSPACE/source');
const probe=spawnSync(process.execPath,['--test','--test-name-pattern=duplicate material IDs|distinct IDs','tests/ai.test.mjs'],{cwd:source,encoding:'utf8',maxBuffer:4*1024*1024});
fs.writeFileSync(path.join(state,'resume-probe.log'),(probe.stdout||'')+(probe.stderr||''));
const result={kind:'main_recovery_helper_result_not_scheduler_proof',head:descriptor.headCommit,trackedFilesMatched:tracked.length,sourceDirectory:source,checkpointMappedCopy:path.join(state,'CHECKPOINT_AS_RECEIVED.json'),draftPreserved:true,draftFixed:false,probeExitCode:probe.status,probePassed:probe.status===0,scheduledResumeVerified:false};
fs.writeFileSync(path.join(state,'RESTORE_RESULT.json'),JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify(result,null,2));
if(probe.status!==0)process.exit(1);
